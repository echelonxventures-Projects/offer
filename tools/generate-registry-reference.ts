/**
 * Generates docs/04-registries/02-reference.md from a live platform.
 *
 * The extension surface is the one piece of documentation that must never drift,
 * because it is what a tenant reads before registering anything. Generating it
 * from `GoipPlatform.describe()` means it cannot be stale by more than one
 * commit, and `npm run docs:check` fails the build if it is.
 */
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { GoipPlatform } from "../src/platform/platform.ts";
import { CAPABILITIES } from "../src/capabilities/descriptors.ts";

const OUT = new URL("../docs/04-registries/02-reference.md", import.meta.url).pathname;

const platform = new GoipPlatform();
const description = platform.describe();

const lines: string[] = [];
const w = (text = "") => lines.push(text);

w("# Registry reference");
w();
w("> Generated by `npm run docs:registries` from a default `GoipPlatform`.");
w("> Do not edit by hand. Run `npm run docs:check` to verify it is current.");
w();
w(`A default deployment ships **${description.registries.length} registries** holding`);
w(`**${description.totalEntries} entries**. Every one of them is an extension point:`);
w("registering an entry adds behaviour without changing any engine.");
w();
w("## Summary");
w();
w("| Registry | Entries | Extends |");
w("| --- | ---: | --- |");

const purpose: Record<string, string> = {
  "economic-unit": "Currencies, points, resources, entitlements",
  "economic-unit-class": "How a family of units behaves",
  "exchange-rate": "Conversions between units",
  chronology: "Tick size and epoch for an instant",
  calendar: "Named fields an instant decomposes into",
  "temporal-zone": "Offsets for field decomposition",
  "spatial-node": "Places, physical and virtual",
  "spatial-node-kind": "Kinds of place",
  "coordinate-system": "Axes and topology for positions",
  reality: "Binding and non-binding execution partitions",
  "rule-operator": "Predicates available to conditions",
  "rule-function": "Value functions available to conditions",
  "benefit-type": "How a benefit's value is computed",
  "effect-kind": "What that value does to the world",
  "funding-model": "How cost divides across funders",
  "party-kind": "Kinds of party that hold budgets",
  "lifecycle-transition": "Legal state moves and their approval gates",
  "decision-objective": "What 'best' means when offers compete",
  policy: "Governance checks before publication",
  "risk-signal": "Inputs to the risk score",
  "attribution-model": "How credit divides across a journey",
  "domain-profile": "Presentation and policy metadata",
  "context-resolver": "Steps that assemble a context",
};

for (const registry of description.registries) {
  w(`| \`${registry.name}\` | ${registry.entries} | ${purpose[registry.name] ?? ""} |`);
}

w();
w("## Entries");
w();

for (const { name } of description.registries) {
  const registry = platform.registries[name];
  if (!registry) continue;
  w(`### \`${name}\``);
  w();
  if (purpose[name]) w(`${purpose[name]}.`);
  w();
  w("| Key | Label | Notes |");
  w("| --- | --- | --- |");
  for (const entry of registry.list()) {
    const described = entry as { key: string; label: string; description?: string };
    const note = (described.description ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ");
    w(`| \`${described.key}\` | ${described.label} | ${note} |`);
  }
  w();
}

w("## Capabilities");
w();
w(`The public surface is fixed at **${CAPABILITIES.length} capabilities**. Unlike the`);
w("registries above, this list is deliberately closed: a new verb is a change to");
w("the platform's contract with its callers, not a configuration change.");
w();
w("| Capability | Phase | Mutating | Financial | Purpose |");
w("| --- | --- | :-: | :-: | --- |");
for (const capability of CAPABILITIES) {
  w(
    `| \`${capability.key}\` | ${capability.phase} | ${capability.mutating ? "yes" : "no"} | ` +
      `${capability.financial ? "yes" : "no"} | ${capability.description ?? ""} |`,
  );
}
w();

const content = lines.join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== content) {
    console.error("docs/04-registries/02-reference.md is out of date. Run: npm run docs:registries");
    process.exit(1);
  }
  console.log("registry reference is current.");
} else {
  writeFileSync(OUT, content);
  console.log(`wrote ${OUT}`);
  console.log(`${description.registries.length} registries, ${description.totalEntries} entries, ${CAPABILITIES.length} capabilities`);
}
